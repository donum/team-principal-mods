"""Turn real later-year team history into game events for a built pack.

A career keeps going after the pack's own season. docs/teams/dtm_game_events.csv
lists what really happened to the DTM grid by calendar year: teams that
joined or left, and engine makes that came and went. This step writes the
rows after the pack's year into the built pack:

- team_leave, team_join, engine_supplier_leave, engine_supplier_join rows
  become events.json entries with an exact incoming season and chance 1.
- A joining team is added to teams.json as an inactive team, cloned from a
  team of the same make (headquarters, tyre deal) or, for a new make, from
  the first team. Its car is generated by the game from
  `entry_performance_tag` when it debuts. Files indexed by team name get a
  copy of the clone's entry.
- A joining engine maker is added to engines.json as an inactive supplier,
  cloned from the supplier it replaces (the previous row's leaver).
- Supplier capacity is raised to the most teams a make has at one time.

season.json "real_history": {
    "events": "docs/teams/dtm_game_events.csv",
    "operators": {"<key>": "<pack team name>", ...},   # the pack's own teams
    "pay_drivers": {"<driver>": amount_m, ...}          # optional
}
Season n of a career is calendar year SEASON_START_YEAR + n - 1.
"""

import copy
import csv
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
MIN_TEAMS = 10
CAPACITY_SPARE = 2
TEAM_EVENTS = ("team_join", "team_leave", "engine_supplier_join", "engine_supplier_leave")


def load_json(path):
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def dump_json(path, data):
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(data, fh, indent=2, ensure_ascii=False)
        fh.write("\n")


def rgb(text):
    return [int(v) for v in text.split()] if text else None


def team_files(out, clone, new):
    """Give the new team a copy of the clone's entry in every team-indexed file."""
    def edit(name, fn):
        path = out / name
        if path.exists():
            data = load_json(path)
            fn(data)
            dump_json(path, data)

    def ownership(d):
        if clone in d:
            d[new] = copy.deepcopy(d[clone])

    def tech(d):
        rows = {t["team"]: t for t in d.get("teams", [])}
        if clone in rows:
            d["teams"].append({**copy.deepcopy(rows[clone]), "team": new})

    def parts(d):
        if clone in d.get("default_contracts", {}):
            d["default_contracts"][new] = copy.deepcopy(d["default_contracts"][clone])

    def ers(d):
        if clone in d.get("starting_levels", {}):
            d["starting_levels"][new] = copy.deepcopy(d["starting_levels"][clone])

    def relationships(d):
        if clone in d:
            d[new] = {}

    edit("team_ownership.json", ownership)
    edit("startingtechnologies.json", tech)
    edit("parts.json", parts)
    edit("ers_development.json", ers)
    edit("relationships.json", relationships)


def planned_teams(manifest, suppliers):
    """Teams that join after the pack's year, as {"name", "engine_supplier"},
    without a built pack (for art tools). `suppliers`: the pack's supplier keys."""
    spec = manifest.get("real_history")
    if not spec:
        return []
    year = int(manifest["constants"]["SEASON_START_YEAR"])
    operators = spec.get("operators", {})
    with open(REPO / spec["events"], encoding="utf-8") as fh:
        rows = [r for r in csv.DictReader(fh) if int(r["year"]) > year]
    by_make = {}
    out = []
    for r in rows:
        if r["event"] == "engine_supplier_join":
            by_make[r["make"]] = r["key"]
        elif r["event"] == "team_join" and r["key"] not in operators:
            out.append({"name": r["name"], "engine_supplier": r["make"] if r["make"] in suppliers else by_make.get(r["make"], r["make"])})
    return out


def apply(out, manifest):
    spec = manifest.get("real_history")
    if not spec:
        return
    year = int(manifest["constants"]["SEASON_START_YEAR"])
    operators = dict(spec.get("operators", {}))
    with open(REPO / spec["events"], encoding="utf-8") as fh:
        rows = [r for r in csv.DictReader(fh) if int(r["year"]) > year]

    teams = load_json(out / "teams.json")
    engines = load_json(out / "engines.json")
    suppliers = engines["suppliers"]
    events = load_json(out / "events.json")
    # Vanilla supplier joins name fictional makers this pack doesn't have.
    events = [e for e in events if not (e.get("type") == "engine_supplier_join" and e.get("supplier") not in suppliers)]
    histories = load_json(out / "team_histories.json")
    make_supplier = {}
    for t in teams:
        make_supplier.setdefault(t.get("engine_supplier"), t["name"])
    added = []
    last_leaver = {}

    for r in rows:
        season = int(r["year"]) - year + 1
        kind, key, make = r["event"], r["key"], r["make"]
        if kind == "team_leave":
            if key not in operators:
                continue  # never on this pack's grid
            events.append({"type": "team_leave", "team": operators[key], "chance": 1.0,
                           "exact_season": season, "guaranteed": True})
        elif kind == "team_join":
            if key in operators:
                continue  # already on the grid in this pack's year
            supplier = make if make in suppliers else next((s for s in suppliers if suppliers[s].get("$make") == make), None)
            if supplier is None:
                sys.exit(f"real_history: no engine supplier for {make!r} ({r['name']}); add an engine_supplier_join row first")
            clone_name = make_supplier.get(supplier) or teams[0]["name"]
            clone = next(t for t in teams if t["name"] == clone_name)
            team = copy.deepcopy(clone)
            team.update({
                "name": r["name"], "active": False, "nationality": r["nationality"] or clone["nationality"],
                "entry_count": int(r["entry_count"]), "entry_performance_tag": r["performance"],
                "previous_constructor_position": None,
                "history": {k: 0 for k in clone.get("history", {})},
                "engine_supplier": supplier, "engine": suppliers[supplier]["engine"],
                "engine_contract_type": "partner" if r["performance"] not in ("backmarker", "lower_midfield") else "customer",
            })
            for field, col in (("color_rgb", "color"), ("secondary_color_rgb", "secondary")):
                if rgb(r[col]):
                    team[field] = rgb(r[col])
            teams.append(team)
            histories[r["name"]] = r["history"]
            team_files(out, clone_name, r["name"])
            operators[key] = r["name"]
            make_supplier.setdefault(supplier, r["name"])
            added.append(r["name"])
            events.append({"type": "team_join", "team": r["name"], "chance": 1.0,
                           "exact_season": season, "guaranteed": True})
        elif kind == "engine_supplier_leave":
            if key not in suppliers:
                continue
            last_leaver[make] = key
            events.append({"type": "engine_supplier_leave", "supplier": key, "chance": 1.0,
                           "exact_season": season, "guaranteed": True})
        elif kind == "engine_supplier_join":
            if key in suppliers:
                continue
            source = next(iter(last_leaver.values()), next(iter(suppliers)))
            rec = copy.deepcopy(suppliers[source])
            rec.update({"active": False, "first_active_season": season, "join_chance": 0.0,
                        "nationality": r["nationality"] or rec.get("nationality"),
                        "engine": r["name"] or rec["engine"], "$make": make})
            suppliers[key] = rec
            events.append({"type": "engine_supplier_join", "supplier": key, "chance": 1.0,
                           "exact_season": season, "guaranteed": True})
        else:
            sys.exit(f"real_history: unknown event {kind!r} in {spec['events']}")

    # Walk the career the way the game does at each rollover: joins first,
    # then leaves in file order. The game never lets the grid drop below
    # MIN_TEAMS active teams (managers.team_leave_events, hard-coded), so a
    # leave that would do that is dropped here instead of silently failing.
    # A supplier that still has a team left stays in the series.
    sup_of = {t["name"]: t.get("engine_supplier") for t in teams}
    active = {t["name"] for t in teams if t.get("active", True)}
    peak = {}
    blocked = []
    kept = []
    seasons = sorted({e["exact_season"] for e in events if "exact_season" in e and e["type"] in TEAM_EVENTS})
    plain = [e for e in events if not ("exact_season" in e and e["type"] in TEAM_EVENTS)]
    for season in seasons:
        batch = [e for e in events if e.get("exact_season") == season and e["type"] in TEAM_EVENTS]
        for e in batch:
            if e["type"] == "team_join":
                active.add(e["team"])
                kept.append(e)
        for e in batch:
            if e["type"] == "team_leave":
                if len(active) - 1 < MIN_TEAMS:
                    blocked.append((season, e["team"], f"the game keeps at least {MIN_TEAMS} teams"))
                    continue
                active.discard(e["team"])
                kept.append(e)
        for e in batch:
            if e["type"] == "engine_supplier_join":
                kept.append(e)
            elif e["type"] == "engine_supplier_leave":
                if any(sup_of.get(t) == e["supplier"] for t in active):
                    blocked.append((season, f"engine {e['supplier']}", "one of its teams is still racing"))
                    continue
                kept.append(e)
        for s in set(sup_of[t] for t in active):
            peak[s] = max(peak.get(s, 0), sum(1 for t in active if sup_of[t] == s))
    events = plain + kept
    # Capacity: the most teams a supplier has at once, plus spare room. With
    # no spare room a scripted join can fail (seen in a rollover test).
    for s, rec in suppliers.items():
        start = sum(1 for t in teams if t.get("active", True) and t.get("engine_supplier") == s)
        rec["capacity"] = max(rec.get("capacity", 0), start, peak.get(s, 0)) + CAPACITY_SPARE
        rec.pop("$make", None)
    for season, what, why in blocked:
        print(f"real history: season {season}: {what} stays, {why}")

    for name, amount in spec.get("pay_drivers", {}).items():
        path = out / "drivers.json"
        drivers = load_json(path)
        hit = next((d for d in drivers if d["name"] == name), None)
        if hit is None:
            sys.exit(f"real_history: pay driver {name!r} is not in drivers.json")
        hit["pay_driver_amount_m"] = amount
        dump_json(path, drivers)

    dump_json(out / "teams.json", teams)
    dump_json(out / "engines.json", engines)
    dump_json(out / "events.json", events)
    dump_json(out / "team_histories.json", histories)
    if added:
        print(f"real history: {len(added)} future team(s): {', '.join(added)}")
